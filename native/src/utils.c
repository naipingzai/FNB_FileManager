static const char b64_table[] =
    "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";

char *utils_base64_encode(const unsigned char *data, int len, int *out_len) {
    if (!data || len < 0) return NULL;
    int olen = 4 * ((len + 2) / 3);
    char *b64 = (char *)malloc(olen + 1);
    if (!b64) return NULL;
    int i = 0, j = 0;
    while (i < len) {
        unsigned int a = i < len ? data[i++] : 0;
        unsigned int b = i < len ? data[i++] : 0;
        unsigned int c = i < len ? data[i++] : 0;
        unsigned int triple = (a << 16) | (b << 8) | c;
        b64[j++] = b64_table[(triple >> 18) & 0x3F];
        b64[j++] = b64_table[(triple >> 12) & 0x3F];
        b64[j++] = (i > len + 1) ? '=' : b64_table[(triple >> 6) & 0x3F];
        b64[j++] = (i > len) ? '=' : b64_table[triple & 0x3F];
    }
    b64[j] = '\0';
    if (out_len) *out_len = olen;
    return b64;
}

char *utils_strdup(const char *s) {
    if (!s) return NULL;
    size_t n = strlen(s) + 1;
    char *d = (char *)malloc(n);
    if (d) memcpy(d, s, n);
    return d;
}

unsigned char *utils_read_file(const char *path, int *out_len) {
    if (!path) return NULL;
    FILE *f = fopen(path, "rb");
    if (!f) return NULL;
    fseek(f, 0, SEEK_END);
    long size = ftell(f);
    fseek(f, 0, SEEK_SET);
    if (size <= 0) { fclose(f); return NULL; }
    unsigned char *buf = (unsigned char *)malloc((size_t)size);
    if (!buf) { fclose(f); return NULL; }
    size_t rd = fread(buf, 1, (size_t)size, f);
    fclose(f);
    if (rd != (size_t)size) { free(buf); return NULL; }
    if (out_len) *out_len = (int)size;
    return buf;
}

char *utils_error_json(const char *msg) {
    size_t len = strlen(msg) + 64;
    char *json = (char *)malloc(len);
    snprintf(json, len, "{\"error\":\"%s\"}", msg);
    return json;
}

void bridge_free_string(char *str) {
    if (str) free(str);
}

